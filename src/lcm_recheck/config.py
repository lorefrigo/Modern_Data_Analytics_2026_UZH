def default_retrain_root(eval_root: str) -> str:
    """The retraining_evaluation folder next to eval_root (default of --retrain_root)."""
    return os.path.join(os.path.dirname(os.path.normpath(eval_root)), RETRAIN_FOLDER)


def model_root(eval_root: str, extra_root: str | None, model: str) -> str:
    """The root that holds `model`'s predictions: extra_root if it has a <model> folder, otherwise eval_root."""
    if extra_root and os.path.isdir(os.path.join(extra_root, model)):
        return extra_root
    return eval_root


def shadowed_models(eval_root: str, extra_root: str | None) -> list[str]:
    """Model folders present in both roots (model_root() reads them from extra_root)."""
    if not extra_root or not os.path.isdir(extra_root):
        return []
    return sorted(m for m in os.listdir(extra_root)
                  if os.path.isdir(os.path.join(extra_root, m)) and os.path.isdir(os.path.join(eval_root, m)))


